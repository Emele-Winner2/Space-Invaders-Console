void Tone(uint32_t frequency, uint32_t duration) {
	if (frequency == 0) {
		TIM1->CCR1 = 0;
	} else {
		TIM1->ARR = (1000000UL / frequency) - 1;
		TIM1->CCR1 = TIM1->ARR / 2;
	}
	HAL_Delay(duration);
}

void noTone() {
	TIM1->CCR1 = 0;
}

// Retro Laser: Quick pitch drop
void playLaser(void) {
	for (int f = 1200; f > 300; f -= 100) {
		Tone(f, 15);
	}
	noTone();
}

// Alien March: Low ominous steps getting slightly faster
void playInvaderStep(int freq) {
	Tone(freq, 80);
	noTone();
	HAL_Delay(40);
}
